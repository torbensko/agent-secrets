#!/bin/bash
set -euo pipefail
cd "$(dirname "$0")/.."
mode="${1:-release}"
[[ "$mode" == release || "$mode" == --unsigned ]] || { echo 'Usage: package.sh [--unsigned]' >&2; exit 1; }
version="$(cat VERSION)"
build_number="${BUILD_NUMBER:-1}"
[[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ && "$build_number" =~ ^[1-9][0-9]*$ ]] || { echo 'Invalid version or build number.' >&2; exit 1; }
mkdir -p dist
stage="$(mktemp -d "$PWD/dist/package.XXXXXX")"
trap 'rm -rf "$stage"' EXIT
common=(-project Secrets.xcodeproj -scheme Secrets -configuration Release -destination 'generic/platform=macOS'
    -derivedDataPath build -disableAutomaticPackageResolution ONLY_ACTIVE_ARCH=NO 'ARCHS=arm64 x86_64'
    "MARKETING_VERSION=$version" "CURRENT_PROJECT_VERSION=$build_number")
app="$PWD/dist/Secrets.app"
# Only replace artifacts generated by this script, never installed copies.
rm -rf "$app"
if [[ "$mode" == release ]]; then
    : "${SIGNING_IDENTITY:?Missing Developer ID Application identity}"
    : "${APPLE_TEAM_ID:?Missing APPLE_TEAM_ID}"
    : "${APPLE_ID:?Missing APPLE_ID}"
    : "${APPLE_ID_PASSWORD:?Missing APPLE_ID_PASSWORD}"
    : "${PROFILE_PATH:?Missing Developer ID provisioning profile}"
    [[ "$SIGNING_IDENTITY" == 'Developer ID Application:'* ]] || { echo 'A Developer ID Application certificate is required.' >&2; exit 1; }
    python3 - <<'PY'
import base64, pathlib
key = pathlib.Path('Config/Updates.xcconfig').read_text().split('SPARKLE_PUBLIC_KEY =', 1)[1].strip()
assert len(base64.b64decode(key, validate=True)) == 32, 'Configure the Sparkle public key first.'
PY
    xcodebuild "${common[@]}" archive -archivePath "$stage/Secrets.xcarchive" \
        CODE_SIGN_STYLE=Manual "CODE_SIGN_IDENTITY=$SIGNING_IDENTITY" "DEVELOPMENT_TEAM=$APPLE_TEAM_ID" \
        SECRETS_UPDATE_CHANNEL=Release CODE_SIGN_ENTITLEMENTS=
    python3 - "$stage/ExportOptions.plist" <<'PY'
import os, plistlib, sys
with open(sys.argv[1], 'wb') as f:
    plistlib.dump({'method': 'developer-id', 'teamID': os.environ['APPLE_TEAM_ID'],
                  'signingStyle': 'manual', 'signingCertificate': os.environ['SIGNING_IDENTITY']}, f)
PY
    # Xcode's export step also re-signs Sparkle's nested services and helpers.
    xcodebuild -exportArchive -archivePath "$stage/Secrets.xcarchive" \
        -exportOptionsPlist "$stage/ExportOptions.plist" -exportPath "$stage/export"
    ditto "$stage/export/Secrets.app" "$app"
    # Xcode refuses its own cloud-managed profile under manual signing, so embed it and re-sign the app ourselves.
    cp "$PROFILE_PATH" "$app/Contents/embedded.provisionprofile"
    python3 - "$stage/Secrets.entitlements" <<'PY'
import os, plistlib, sys
team = os.environ['APPLE_TEAM_ID']
with open(sys.argv[1], 'wb') as f:
    plistlib.dump({'com.apple.application-identifier': f'{team}.com.torbensko.secrets',
                   'com.apple.developer.team-identifier': team,
                   'keychain-access-groups': [f'{team}.com.torbensko.secrets']}, f)
PY
    codesign --force --sign "$SIGNING_IDENTITY" --options runtime --timestamp \
        --entitlements "$stage/Secrets.entitlements" "$app"
else
    xcodebuild "${common[@]}" build CODE_SIGN_IDENTITY=- CODE_SIGN_STYLE=Manual \
        CODE_SIGN_ENTITLEMENTS= DEVELOPMENT_TEAM= ENABLE_HARDENED_RUNTIME=NO SECRETS_UPDATE_CHANNEL=Development
    ditto build/Build/Products/Release/Secrets.app "$app"
fi
for arch in arm64 x86_64; do
    lipo "$app/Contents/MacOS/Secrets" -verify_arch "$arch"
done
codesign --verify --deep --strict "$app"
if [[ "$mode" == release ]]; then
    # The shipped app must carry the Keychain entitlement and the profile that authorises it.
    codesign -d --entitlements - "$app" 2>/dev/null | grep -q "$APPLE_TEAM_ID.com.torbensko.secrets" \
        || { echo 'The exported app is missing its keychain-access-groups entitlement.' >&2; exit 1; }
    [[ -f "$app/Contents/embedded.provisionprofile" ]] || { echo 'The exported app is missing its provisioning profile.' >&2; exit 1; }
fi
notarize() {
    xcrun notarytool submit "$1" --apple-id "$APPLE_ID" --password "$APPLE_ID_PASSWORD" \
        --team-id "$APPLE_TEAM_ID" --wait --timeout 30m --output-format json > "$2"
    python3 - "$2" <<'PY'
import json, sys
with open(sys.argv[1]) as f: result = json.load(f)
if result.get('status') != 'Accepted':
    sys.exit(f"Notarization failed: {result.get('id')} {result.get('status')}. Inspect the notarytool log before retrying.")
PY
}
suffix=-unsigned
if [[ "$mode" == release ]]; then
    suffix=''
    ditto -c -k --keepParent "$app" "$stage/submission.zip"
    notarize "$stage/submission.zip" "$PWD/dist/notary-app.json"
    xcrun stapler staple "$app"
    xcrun stapler validate "$app"
    spctl --assess --type execute --verbose "$app"
fi
mkdir "$stage/image"
ditto "$app" "$stage/image/Secrets.app"
ln -s /Applications "$stage/image/Applications"
hdiutil create -volname Secrets -srcfolder "$stage/image" -ov -format UDZO "dist/Secrets${suffix}.dmg"
if [[ "$mode" == release ]]; then
    codesign --force --sign "$SIGNING_IDENTITY" --timestamp dist/Secrets.dmg
    notarize dist/Secrets.dmg "$PWD/dist/notary-dmg.json"
    xcrun stapler staple dist/Secrets.dmg
    xcrun stapler validate dist/Secrets.dmg
fi
ditto -c -k --keepParent "$app" "dist/Secrets${suffix}.zip"
(cd dist && shasum -a 256 "Secrets${suffix}.dmg" "Secrets${suffix}.zip" > "SHA256SUMS${suffix}.txt")
echo "Packaged dist/Secrets${suffix}.dmg"
